    private void showScreen(javax.swing.JInternalFrame newScreen) {
        // 1. If a screen is already open, close it completely!
        if (currentScreen != null) {
            currentScreen.dispose(); 
            desktop.remove(currentScreen);
        }
        
        // 2. Set the new screen as the current one, add it, and show it
        currentScreen = newScreen;
        desktop.add(currentScreen);
        currentScreen.show();
    }
