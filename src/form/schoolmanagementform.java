     public void clock(){
            
            Thread clock = new Thread(){
                @Override
                 public void run(){
                     try {
                    while (true){
                        SimpleDateFormat sdfd = new SimpleDateFormat("EEEE, dd/MMMM/YYYY");
                        SimpleDateFormat sdft = new SimpleDateFormat("HH:MM:ss:SS a");
                        lbdate.setText("Date : "+sdfd.format(new java.util.Date()));
                         lbtime.setText("Time : "+sdft.format(new java.util.Date()));
                        sleep(100);
                                
                    }
                
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            }     
                     
            }
                
            };
            clock.start();
                    }
