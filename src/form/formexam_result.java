    private void tableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableMouseClicked
       int row = table.getSelectedRow();
        
        // Grab the IDs from the clicked row
        String student_id = table.getValueAt(row, 0).toString();
        String exam_id = table.getValueAt(row, 1).toString();
        String course_id = table.getValueAt(row, 2).toString();
        String marks = table.getValueAt(row, 3).toString();
        
        // Put the marks in the text box
        txtmarks.setText(marks);
             
        try {
            // Use single quotes ' - ' for cloud strict mode to select the comboboxes
            sql = "SELECT CONCAT(student_id, ' - ', lname) AS student FROM tbstudent WHERE student_id = " + student_id;
            ps = connectionDB.getConnection().prepareStatement(sql);
            r = ps.executeQuery();
            if(r.next()) combostudentid.setSelectedItem(r.getString("student"));
            
            sql = "SELECT CONCAT(exam_id, ' - ', name) AS exam FROM tbexam WHERE exam_id = " + exam_id;
            ps = connectionDB.getConnection().prepareStatement(sql);
            r = ps.executeQuery();
            if(r.next()) comboexamid.setSelectedItem(r.getString("exam"));
            
            sql = "SELECT CONCAT(course_id, ' - ', name) AS course FROM tbcourse WHERE course_id = " + course_id;
            ps = connectionDB.getConnection().prepareStatement(sql);
            r = ps.executeQuery();
            if(r.next()) combocourseid.setSelectedItem(r.getString("course"));
            
            ps.close();
            r.close();
        } catch (Exception e) {
            e.printStackTrace();
        } // TODO add your handling code here:
    }//GEN-LAST:event_tableMouseClicked


