    public TableModel select(){
        try {
            // FIX: Explicitly name the columns so the auto-ID doesn't mess up the order
            sql="SELECT student_id, exam_id, course_id, marks FROM tbexam_result";
            ps=connectionDB.getConnection().prepareStatement(sql);
            r=ps.executeQuery();
            while(r.next()){
                // Now Column 1 is definitely Student ID!
                String student_id = r.getString(1);
                String exam_id    = r.getString(2);
                String course_id  = r.getString(3);
                String marks      = r.getString(4);
                
                String []row = {student_id, exam_id, course_id, marks};
                
                mod=(DefaultTableModel)table.getModel();
                mod.addRow(row);
            }
            return mod;
        } catch (Exception e) {
            e.printStackTrace();
            return null;
        }
    }
