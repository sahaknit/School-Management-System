    public TableModel select(){
        try {
            sql="SELECT * FROM tbclassroom";
            ps=connectionDB.getConnection().prepareStatement(sql);
            r=ps.executeQuery();
            while(r.next()){
                String classroom = r.getString(1);
                String student_id=r.getString(2);
                String year=r.getString(3);
                String grade_id=r.getString(4);
                String semester= r.getString(5);
                String status = r.getString(6);
                String remarks = r.getString(7);
                String teacher_id = r.getString(8);
               
                String []row = {classroom,grade_id,student_id,teacher_id,year,semester, remarks, status };
                
                mod=(DefaultTableModel)table.getModel();
                mod.addRow(row);
                
            }
            return mod;
        } catch (Exception e) {
            e.printStackTrace();
            return null;
        }
    }
