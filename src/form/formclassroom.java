            sql="SELECT CONCAT(R.student_id,' - ',lname) AS student FROM tbclassroom AS R INNER JOIN tbstudent AS RT ON R.student_id=RT.student_id "
                    + "WHERE classroom_id="+txtclassroomid.getText()+"";
        ps = connectionDB.getConnection().prepareStatement(sql);
        r = ps.executeQuery();
        while(r.next()){
            String studenttmp = r.getString("student");
            Combostudentid.setSelectedItem(studenttmp);
        }
        ps.close();
        r.close();
